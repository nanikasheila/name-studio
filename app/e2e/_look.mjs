import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { createServer } from "vite";
const root = fileURLToPath(new URL("..", import.meta.url));
const out = process.argv[2];
const text = readFileSync("/mnt/project-files/name-studio-ep4/ユメノストラ第4話_周回9_v4.namestudio", "utf8");
const server = await createServer({ root, logLevel: "error", server: { port: 1440, strictPort: false } });
await server.listen();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
await page.addInitScript({ path: fileURLToPath(new URL("tauri-mock.js", import.meta.url)) });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(server.resolvedUrls.local[0]);
await page.waitForFunction(() => window.nameStudio);
await page.evaluate((text) => { localStorage.clear(); window.nameStudio.show(JSON.parse(text)); }, text);
await page.waitForTimeout(800);
const settle = () => page.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))));
const at = (n, mm) => page.evaluate(([n, mm]) => window.nameStudio.workbench.editor.clientOf(window.nameStudio.workbench.project.pages[n - 1].id, mm), [n, mm]);
await page.click("#continuous-mode");
await page.waitForTimeout(600);
await page.evaluate(() => { const e = window.nameStudio.workbench.editor; e.setRows(4); e.fitAll(false); e.draw(); });
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/1 continuous.png` });
// pen sketch above page 3
await page.evaluate(() => window.nameStudio.workbench.setTool("pen"));
const pts = [[40, -30], [80, -60], [120, -25], [160, -55]];
const scr = await Promise.all(pts.map((p) => at(3, p)));
await page.mouse.move(...scr[0]); await page.mouse.down();
for (const p of scr.slice(1)) for (let s = 1; s <= 6; s++) await page.mouse.move(p[0], p[1]);
await page.mouse.up(); await settle();
// sticky above page 4
await page.evaluate(() => window.nameStudio.workbench.setTool("sticky"));
await page.mouse.click(...(await at(4, [30, -40]))); await settle();
await page.keyboard.type("ここで回想？");
await page.evaluate(() => window.nameStudio.workbench.setTool("select"));
// hold panel 1 of page 5
await page.evaluate(() => { const wb = window.nameStudio.workbench; const p = wb.project.pages[4]; wb.editor.select({ kind: "panel", pageId: p.id, id: p.panels[0].id }); });
await settle();
await page.locator(".action-bar button", { hasText: "保留" }).first().click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/2 aside.png` });
await page.evaluate(() => { const e = window.nameStudio.workbench.editor; e.fitAll(false); e.draw(); });
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/3 fit all.png` });
await page.evaluate(() => { const e = window.nameStudio.workbench.editor; e.setRows(1); e.showPage(4); e.fitRows(); e.draw(); });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/4 one row.png` });
const info = await page.evaluate(() => ({ room: window.nameStudio.workbench.editor.room, held: window.nameStudio.workbench.project.held?.map((h) => [h.near, h.at]), stick: window.nameStudio.workbench.project.pages[3].stickies }));
console.log(JSON.stringify(info), errors);
await browser.close(); await server.close();

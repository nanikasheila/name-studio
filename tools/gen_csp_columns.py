"""Make app/src/generated/csp-columns.ts: what each setting of a CSP pen or
eraser is (its palette group and label as CSP shows them, its values) and
how the brush settings edit it, from csp-format's
docs/assets/spec/subtool-columns.tsv (at the rev Cargo.toml names).

    python tools/gen_csp_columns.py PATH/TO/subtool-columns.tsv app/src/generated/csp-columns.ts
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

# Lists of choices: "0 なし, 1 弱, 2 中, 3 強", optionally after a lead-in
# such as "CSP の並び順" and with notes in （）.
CHOICE = re.compile(r"(-?\d+) ([^,（(]+?)(?:（[^）]*）)?(?=,|$|（)")
LEAD_IN = re.compile(r"^(?:CSP の並び順|一覧の並び順|ボタンの並び順)\s*")
RANGE = re.compile(r"(-?\d+(?:\.\d+)?)–(-?\d+(?:\.\d+)?)")


def edit_of(row: dict[str, str]) -> dict:
    values = row["values"].strip()
    blob = row["blob"].split(":")[0]
    if blob == "effector":
        return {"kind": "effector"}
    if blob == "materials":
        return {"kind": "materials"}
    if blob or row["type"] == "BLOB":
        return {"kind": "fixed"}
    if row["type"] == "TEXT":
        return {"kind": "text"}
    if values.startswith("0/1"):
        return {"kind": "check"}
    if values.startswith("ビット") or values in ("未解明",):
        return {"kind": "number", "integer": True}
    plain = LEAD_IN.sub("", values)
    plain = re.sub(r"（[^）]*確認[^）]*）$", "", plain)
    choices = CHOICE.findall(plain)
    if len(choices) >= 2 and re.match(r"^-?\d+ ", plain):
        return {"kind": "choice", "options": [[int(v), label.strip()] for v, label in choices]}
    edit: dict = {"kind": "number", "integer": row["type"] == "INTEGER"}
    found = RANGE.search(values)
    if found:
        edit["min"], edit["max"] = float(found.group(1)), float(found.group(2))
    if "%" in values:
        edit["unit"] = "%"
    elif values.startswith("度"):
        edit["unit"] = "°"
    elif values.startswith("倍"):
        edit["unit"] = "倍"
    return edit


def main(tsv: str, out: str) -> None:
    rows = list(csv.DictReader(Path(tsv).open(encoding="utf-8"), delimiter="\t"))
    columns = []
    for row in rows:
        kinds = set(row["kinds"].split(","))
        if not kinds & {"brush", "eraser"} or row["group"] == "（内部）":
            continue
        columns.append(
            {
                "column": row["column"],
                "group": row["group"],
                "label": row["label"],
                "values": row["values"],
                "sure": row["certainty"].startswith("確認済み"),
                "edit": edit_of(row),
            }
        )
    body = ",\n".join("  " + json.dumps(c, ensure_ascii=False) for c in columns)
    text = f"""// Generated by tools/gen_csp_columns.py from csp-format's
// docs/assets/spec/subtool-columns.tsv; do not edit.

/** How the brush settings edit a column. */
export type CspEdit =
  | {{ kind: "check" }}
  | {{ kind: "choice"; options: [number, string][] }}
  | {{ kind: "number"; integer: boolean; min?: number; max?: number; unit?: string }}
  | {{ kind: "text" }}
  | {{ kind: "effector" }}
  | {{ kind: "materials" }}
  | {{ kind: "fixed" }};

/** A setting of CSP's pens and erasers, as CSP's sub tool detail palette shows it. */
export interface CspColumn {{
  column: string;
  /** Palette group (ブラシサイズ, インク, 入り抜き…). */
  group: string;
  /** The item as CSP labels it. */
  label: string;
  /** What the values mean. */
  values: string;
  /** Checked in CSP (else inferred from the name and the palette). */
  sure: boolean;
  edit: CspEdit;
}}

export const CSP_COLUMNS: readonly CspColumn[] = [
{body},
];
"""
    Path(out).write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])

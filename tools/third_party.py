"""Write THIRD_PARTY_NOTICES.md: the libraries the app is built from.

Why: name-studio is distributed (MIT, see LICENSE) with libraries whose
     licenses ask for their notice to come along. The list goes into the
     installer next to LICENSE.
How: The Rust crates the Windows app links (normal and build dependencies of
     name-studio-app, from ``cargo metadata``) and the npm packages bundled
     into its page (production dependencies in app/package-lock.json), each
     with its version, license and home page.

Usage (from the repository root, after changing dependencies):
    python tools/third_party.py
CI runs it with ``--check`` and fails when the file is out of date.
"""
from __future__ import annotations

import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
APP = "name-studio-app"


def crates() -> list[tuple[str, str, str, str]]:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    ours = set(meta["workspace_members"])
    root = next(i for i in ours if packages[i]["name"] == APP)
    seen: set[str] = set()
    stack = [root]
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            if any(kind["kind"] in (None, "build") for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    rows = []
    for i in seen - ours:
        p = packages[i]
        home = p.get("repository") or p.get("homepage") or ""
        rows.append((p["name"], p["version"], p.get("license") or "（記載なし）", home))
    return sorted(rows, key=lambda row: (row[0].lower(), row[1]))


def npm() -> list[tuple[str, str, str, str]]:
    lock = json.loads((ROOT / "app" / "package-lock.json").read_text(encoding="utf-8"))
    rows = []
    for path, p in lock["packages"].items():
        if not path or p.get("dev") or p.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        rows.append((name, p.get("version", ""), p.get("license") or "（記載なし）", f"https://www.npmjs.com/package/{name}"))
    return sorted(rows)


def table(rows: list[tuple[str, str, str, str]]) -> list[str]:
    lines = ["| 名前 | 版 | ライセンス | 入手先 |", "|---|---|---|---|"]
    lines += [f"| {name} | {version} | {license.replace('|', '/')} | {home} |" for name, version, license, home in rows]
    return lines


def render() -> str:
    lines = [
        "# 使っているライブラリ（Third-party notices）",
        "",
        "Name Studio は以下のライブラリを組み込んで配布しています。各ライブラリの著作権はそれぞれの作者にあり、",
        "それぞれのライセンス（入手先に全文があります）に従います。Name Studio 自体のライセンスは [LICENSE](LICENSE)（MIT）です。",
        "",
        "Name Studio bundles the libraries below. Each is the copyright of its authors and is used under its own",
        "license, whose full text is at the linked source. Name Studio itself is under the MIT license (LICENSE).",
        "",
        "SQLite（rusqlite に同梱）はパブリックドメインです。SQLite (bundled by rusqlite) is in the public domain.",
        "",
        "このファイルは `python tools/third_party.py` で作っています。This file is generated by `python tools/third_party.py`.",
        "",
        "## 画面（npm）",
        "",
        *table(npm()),
        "",
        "## アプリ本体（Rust）",
        "",
        *table(crates()),
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("THIRD_PARTY_NOTICES.md is out of date: run python tools/third_party.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
